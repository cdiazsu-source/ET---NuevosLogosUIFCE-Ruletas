// Builds src/components/SlotReel/slot-reel-logo.html: one self-contained file (React + GSAP + logo paths inlined).
// Run:  npm run build:web
import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const result = await build({
  entryPoints: ["src/components/SlotReel/web-lockup.tsx"],
  bundle: true, minify: true, format: "iife", write: false, jsx: "automatic",
  loader: { ".json": "json" }, define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>UIFCE Slot Reel Logo</title>
<style>
  html, body, #root { margin: 0; width: 100%; height: 100%; overflow: hidden; }
  body { background: #262E6B; }   /* preview backdrop only — the component itself is transparent */
</style>
</head>
<body>
<!-- Generated by scripts/build-web.mjs from SlotReelLockup.tsx — edit the component, then npm run build:web -->
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;
writeFileSync("src/components/SlotReel/slot-reel-logo.html", html);
console.log(`slot-reel-logo.html written (${(html.length / 1024).toFixed(0)} KB)`);
